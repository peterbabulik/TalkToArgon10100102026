if TORCH_AVAILABLE:

    class HurwitzFanoLinear(nn.Module):
        """
        8D Block-Orthogonal Hurwitz-Radon Linear Layer.

        Instead of storing a dense (out_features x in_features) matrix, each 8x8 block
        is parameterized by an 8D octonion weight w_b in R^8 expanded via the
        Hurwitz-Radon left-multiplication operator L(w_b).

        Key Advantages:
          1. 8:1 Parameter Compression (D_in * D_out / 8 parameters).
          2. Exact Spectral Norm Control: every 8x8 block satisfies
             L(w)^T L(w) = ||w||_2^2 I_8. When w is normalized to unit norm,
             every 8x8 block is strictly orthogonal (isometry -> no exploding/vanishing
             gradients in deep recurrent or residual stacks).
          3. Full 8D cross-channel mixing dictated by the Fano plane PG(2,2).
        """

        def __init__(
            self,
            in_features: int,
            out_features: int,
            bias: bool = True,
            unit_norm_weights: bool = False,
        ):
            super().__init__()
            assert in_features % 8 == 0, "in_features must be divisible by 8"
            assert out_features % 8 == 0, "out_features must be divisible by 8"

            self.in_features = in_features
            self.out_features = out_features
            self.in_blocks = in_features // 8
            self.out_blocks = out_features // 8
            self.unit_norm_weights = unit_norm_weights

            # Register the 8x8x8 Hurwitz-Radon basis tensor as a non-trainable buffer
            self.register_buffer(
                "basis_L",
                torch.tensor(HURWITZ_BASIS_L, dtype=torch.float32),
            )

            # Weight tensor: (out_blocks, in_blocks, 8) -> 8x fewer params than dense
            self.oct_weight = nn.Parameter(
                torch.randn(self.out_blocks, self.in_blocks, 8) / np.sqrt(self.in_blocks * 8)
            )
            if bias:
                self.bias = nn.Parameter(torch.zeros(out_features))
            else:
                self.register_parameter("bias", None)

        def get_block_matrix(self) -> torch.Tensor:
            """Assemble the full (out_features, in_features) Hurwitz block matrix."""
            w = self.oct_weight
            if self.unit_norm_weights:
                w = F.normalize(w, p=2, dim=-1) / np.sqrt(self.in_blocks)
            # Expand (out_blocks, in_blocks, 8) -> (out_blocks, in_blocks, 8, 8)
            blocks = torch.einsum("oik,kmn->oimn", w, self.basis_L)
            # Reshape to (out_blocks * 8, in_blocks * 8)
            return blocks.permute(0, 2, 1, 3).reshape(self.out_features, self.in_features)

        def forward(self, x: torch.Tensor) -> torch.Tensor:
            W = self.get_block_matrix()
            return F.linear(x, W, self.bias)

        def associator_regularization(
            self, x: torch.Tensor, y: torch.Tensor, z: torch.Tensor
        ) -> torch.Tensor:
            """
            Differentiable Octonion Associator [x, y, z] over 8D blocks.
            Can be maximized to encourage non-associative tree sensitivity or
            penalized to project onto quaternionic associative submanifolds.
            """
            x8 = x.reshape(*x.shape[:-1], -1, 8)
            y8 = y.reshape(*y.shape[:-1], -1, 8)
            z8 = z.reshape(*z.shape[:-1], -1, 8)

            def _mul(a: torch.Tensor, b: torch.Tensor) -> torch.Tensor:
                return torch.einsum("...bi,ikj,...bj->...bk", a, self.basis_L, b)

            xy_z = _mul(_mul(x8, y8), z8)
            x_yz = _mul(x8, _mul(y8, z8))
            return xy_z - x_yz


