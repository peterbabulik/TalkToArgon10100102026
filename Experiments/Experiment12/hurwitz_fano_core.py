# 1. CANONICAL FANO PLANE PG(2,2) & HURWITZ-RADON GENERATORS
# ============================================================================
# Basis: e_0 = 1 (real scalar), and 7 imaginary units e_1 ... e_7.
# Canonical cyclic Fano triples (i, j, k) such that e_i * e_j = +e_k,
# generated by cyclic shifts of (1, 2, 4) mod 7:
FANO_LINES: Tuple[Tuple[int, int, int], ...] = (
    (1, 2, 4),
    (2, 3, 5),
    (3, 4, 6),
    (4, 5, 7),
    (5, 6, 1),
    (6, 7, 2),
    (7, 1, 3),
)


def _build_multiplication_tables() -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    """
    Build the 8x8 index table, 8x8 sign table, and the 8x8x8 structure
    tensor C[i, j, k] where e_i * e_j = sum_k C[i, j, k] e_k.

     Also returns the 8 Hurwitz-Radon basis matrices B_0 ... B_7 in R^{8x8}
    satisfying:
        B_0 = I_8
        B_i^T = -B_i,  B_i^2 = -I_8         (for i = 1..7)
        B_i B_j + B_j B_i = -2 delta_ij I_8 (for i, j = 1..7)
    """
    idx_table = np.zeros((8, 8), dtype=np.int64)
    sign_table = np.zeros((8, 8), dtype=np.float64)

    # e_0 * e_i = e_i, e_i * e_0 = e_i
    for i in range(8):
        idx_table[0, i] = i
        idx_table[i, 0] = i
        sign_table[0, i] = 1.0
        sign_table[i, 0] = 1.0

    # e_i * e_i = -e_0 for i = 1..7
    for i in range(1, 8):
        idx_table[i, i] = 0
        sign_table[i, i] = -1.0

    # Directed Fano triples
    for a, b, c in FANO_LINES:
        # Even permutations (+1)
        for i, j, k in ((a, b, c), (b, c, a), (c, a, b)):
            idx_table[i, j] = k
            sign_table[i, j] = 1.0
        # Odd permutations (-1)
        for i, j, k in ((b, a, c), (c, b, a), (a, c, b)):
            idx_table[i, j] = k
            sign_table[i, j] = -1.0

    # Basis matrices B_i (8, 8, 8): (B_i)_{k, j} = coefficient of e_k in e_i * e_j
    # So left-multiplication L(x) y = (sum_i x_i B_i) y
    basis_L = np.zeros((8, 8, 8), dtype=np.float64)
    basis_R = np.zeros((8, 8, 8), dtype=np.float64)
    for i in range(8):
        for j in range(8):
            k = idx_table[i, j]
            s = sign_table[i, j]
            basis_L[i, k, j] = s  # L(e_i) e_j = s * e_k
            basis_R[j, k, i] = s  # R(e_j) e_i = s * e_k

    return idx_table, sign_table, basis_L, basis_R


IDX_TABLE, SIGN_TABLE, HURWITZ_BASIS_L, HURWITZ_BASIS_R = _build_multiplication_tables()


