# 6. SELF-TEST SUITE (ALGEBRAIC & GEOMETRIC VERIFICATION)
# ============================================================================
def _run_self_tests() -> None:
    print("=" * 72)
    print("8D HURWITZ-FANO ALGEBRAIC CORE — VERIFICATION SUITE")
    print("=" * 72)
    rng = np.random.RandomState(42)

    # 1. Verify Hurwitz-Radon Matrix Anticommutation: B_i B_j + B_j B_i = -2 delta_ij I_8
    I8 = np.eye(8)
    for i in range(1, 8):
        Bi = HURWITZ_BASIS_L[i]
        assert np.allclose(Bi.T, -Bi), f"B_{i} not skew-symmetric"
        assert np.allclose(Bi @ Bi, -I8), f"B_{i}^2 != -I_8"
        for j in range(i + 1, 8):
            Bj = HURWITZ_BASIS_L[j]
            anticomm = Bi @ Bj + Bj @ Bi
            assert np.allclose(anticomm, 0.0), f"{{B_{i}, B_{j}}} != 0"
    print("[PASS] 1. Clifford / Hurwitz-Radon generators B_1..B_7 anticommute.")

    # 2. Verify Hurwitz Norm Composition: ||x * y||_2 == ||x||_2 * ||y||_2
    x = rng.randn(100, 8)
    y = rng.randn(100, 8)
    xy = oct_mul(x, y)
    lhs = np.linalg.norm(xy, axis=-1)
    rhs = np.linalg.norm(x, axis=-1) * np.linalg.norm(y, axis=-1)
    max_err = np.max(np.abs(lhs - rhs))
    assert max_err < 1e-12, f"Norm composition failed: max_err={max_err}"
    print(f"[PASS] 2. Hurwitz Norm Composition ||x*y|| == ||x||*||y|| (max_err={max_err:.2e}).")

    # 3. Verify Orthogonality of L(x) and R(x): L(x)^T L(x) == ||x||^2 I_8
    Lx = left_matrix(x[0])
    Rx = right_matrix(x[0])
    n2 = oct_norm_sq(x[0])
    assert np.allclose(Lx.T @ Lx, n2 * I8), "L(x)^T L(x) != ||x||^2 I_8"
    assert np.allclose(Rx.T @ Rx, n2 * I8), "R(x)^T R(x) != ||x||^2 I_8"
    assert np.allclose(Lx @ y[0], oct_mul(x[0], y[0])), "L(x)y != x*y"
    assert np.allclose(Rx @ y[0], oct_mul(y[0], x[0])), "R(x)y != y*x"
    print("[PASS] 3. Left/Right 8x8 operator orthogonality L(x)^T L(x) = ||x||^2 I_8.")

    # 4. Verify Division Algebra Inverse: x * x^{-1} == e_0 == x^{-1} * x
    e0 = np.array([1.0, 0, 0, 0, 0, 0, 0, 0])
    x_inv = oct_inv(x)
    prod_r = oct_mul(x, x_inv)
    prod_l = oct_mul(x_inv, x)
    assert np.allclose(prod_r, e0), "x * x^{-1} != e_0"
    assert np.allclose(prod_l, e0), "x^{-1} * x != e_0"
    print("[PASS] 4. Multiplicative inverse x * x^-1 = e_0 verified.")

    # 5. Verify Alternativity & Non-Associativity
    z = rng.randn(100, 8)
    alt_l = oct_associator(x, x, y)
    alt_r = oct_associator(y, x, x)
    assoc_xyz = oct_associator(x, y, z)
    assert np.allclose(alt_l, 0.0, atol=1e-12), "Left alternativity failed"
    assert np.allclose(alt_r, 0.0, atol=1e-12), "Right alternativity failed"
    mean_assoc_norm = float(np.mean(np.linalg.norm(assoc_xyz, axis=-1)))
    assert mean_assoc_norm > 1.0, "Octonions should be non-associative on generic triples!"
    print(f"[PASS] 5. Alternativity [x,x,y]=0 & Non-Associativity ||[x,y,z]||={mean_assoc_norm:.2f}>0.")

    # 6. Verify all 3 Moufang Loop Identities
    # M1: z * (x * (z * y)) == ((z * x) * z) * y
    m1_l = oct_mul(z, oct_mul(x, oct_mul(z, y)))
    m1_r = oct_mul(oct_mul(oct_mul(z, x), z), y)
    # M2: ((x * z) * y) * z == x * (z * (y * z))
    m2_l = oct_mul(oct_mul(oct_mul(x, z), y), z)
    m2_r = oct_mul(x, oct_mul(z, oct_mul(y, z)))
    # M3: (z * x) * (y * z) == z * ((x * y) * z)
    m3_l = oct_mul(oct_mul(z, x), oct_mul(y, z))
    m3_r = oct_mul(z, oct_mul(oct_mul(x, y), z))
    assert np.allclose(m1_l, m1_r, atol=1e-11), "Moufang identity 1 failed"
    assert np.allclose(m2_l, m2_r, atol=1e-11), "Moufang identity 2 failed"
    assert np.allclose(m3_l, m3_r, atol=1e-11), "Moufang identity 3 failed"
    print("[PASS] 6. All three Moufang Loop identities verified to machine precision.")

    # 7. Verify PyTorch HurwitzFanoLinear if available
    if TORCH_AVAILABLE:
        layer = HurwitzFanoLinear(64, 64, unit_norm_weights=True)
        inp = torch.randn(16, 64)
        out = layer(inp)
        assert out.shape == (16, 64)
        dense_params = 64 * 64
        hurwitz_params = layer.oct_weight.numel()
        print(f"[PASS] 7. PyTorch HurwitzFanoLinear: {hurwitz_params} params vs {dense_params} dense (8:1 compression).")

    print("=" * 72)
    print("ALL HURWITZ-FANO SELF-TESTS PASSED.")
    print("=" * 72)


