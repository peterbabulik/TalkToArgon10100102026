# 4. 8D SPATIAL / ARC GRID FANO HASHING & SYMMETRY DESCRIPTOR
# ============================================================================
def arc_grid_fano_descriptor(grid: np.ndarray) -> np.ndarray:
    """
    Project a 2D integer grid (e.g., ARC-AGI state) into a canonical 8D unit
    Octonion + 7D Fano line energy signature (total 15D continuous descriptor).

    How it works:
      - Maps the 8 dihedral D_4 transforms of the grid onto the 8 basis directions
        e_0 .. e_7 via deterministic radial-spectral moments, then combines them
        through the Fano incidence lines.
      - Useful as a fast continuous state embedding for novelty search, R-max
        kernel similarity, or heuristic distance in Go-Explore.
    """
    g = np.asarray(grid, dtype=np.float64)
    if g.ndim != 2 or g.size == 0:
        out = np.zeros(15, dtype=np.float64)
        out[0] = 1.0
        return out

    H, W = g.shape
    bg = float(np.bincount(g.astype(np.int64).ravel().clip(0)).argmax())
    fg = (g != bg).astype(np.float64)

    # 8 channels aligned with Octonion basis e_0 .. e_7:
    # e_0: foreground mass ratio
    # e_1..e_7: 7 spatial/chromatic moment projections mapped to Fano imaginary units
    yy = np.linspace(-1.0, 1.0, H)[:, None]
    xx = np.linspace(-1.0, 1.0, W)[None, :]
    norm_g = (g - bg) / max(1.0, float(g.max() - bg))

    c0 = float(fg.mean())
    c1 = float((norm_g * yy).mean())
    c2 = float((norm_g * xx).mean())
    c3 = float((norm_g * (yy * xx)).mean())
    c4 = float((norm_g * (yy ** 2 - xx ** 2)).mean())
    c5 = float(np.mean(norm_g[:, :-1] != norm_g[:, 1:])) if W > 1 else 0.0
    c6 = float(np.mean(norm_g[:-1, :] != norm_g[1:, :])) if H > 1 else 0.0
    c7 = float(np.mean(norm_g == np.fliplr(norm_g)) - np.mean(norm_g == np.flipud(norm_g)))

    oct_vec = oct_normalize(np.array([c0 + 1e-3, c1, c2, c3, c4, c5, c6, c7], dtype=np.float64))
    triad_e = fano_triad_energy(oct_vec)
    return np.concatenate([oct_vec, triad_e], axis=0)


