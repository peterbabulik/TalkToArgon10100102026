# 3. NON-ASSOCIATIVE STATE RECURRENCE & TREE-SENSITIVE HASHING
# ============================================================================
class HurwitzTrajectoryTracker:
    """
    Norm-preserving, non-associative trajectory accumulator on S^7.
    Because octonions are non-associative, left-accumulation:
        h_{t} = normalize(a_t * h_{t-1})
    and bracketed / hierarchical composition:
        (a_3 * a_2) * a_1  !=  a_3 * (a_2 * a_1)
    distinguish both action ordering (non-commutativity) AND hierarchical
    phrase/sub-goal grouping (non-associativity) without norm explosion or vanishing.
    """

    def __init__(self, seed: int = 1337):
        self.rng = np.random.RandomState(seed)
        self.action_codebook: Dict[Tuple, np.ndarray] = {}
        self.reset()

    def reset(self) -> np.ndarray:
        self.state = np.zeros(8, dtype=np.float64)
        self.state[0] = 1.0  # Identity element e_0
        return self.state.copy()

    def encode_token(self, token: Tuple) -> np.ndarray:
        """Deterministically map a discrete action/event tuple to a unit octonion on S^7."""
        if token not in self.action_codebook:
            # Deterministic hash -> seed -> unit octonion with non-trivial imaginary part
            h = hash(token) & 0xFFFFFFFF
            local_rng = np.random.RandomState(h)
            v = local_rng.randn(8)
            v[0] *= 0.5  # Keep rotation angle away from trivial identity
            self.action_codebook[token] = oct_normalize(v)
        return self.action_codebook[token]

    def step(self, token: Tuple) -> np.ndarray:
        """Left-multiply state by unit octonion of token: h_{t} = u(token) * h_{t-1}."""
        u = self.encode_token(token)
        self.state = oct_normalize(oct_mul(u, self.state))
        return self.state.copy()

    def moufang_conjugate_step(self, token: Tuple) -> np.ndarray:
        """
        Bimultiplication / Moufang loop update:
            h_{t} = (u * h_{t-1}) * u
        Well-defined and parenthesis-free due to Octonion Alternativity:
            (u * h) * u == u * (h * u).
        """
        u = self.encode_token(token)
        self.state = oct_normalize(oct_mul(oct_mul(u, self.state), u))
        return self.state.copy()


